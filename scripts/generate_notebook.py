            "    tokenizer.pad_token = tokenizer.eos_token\n",
            "\n",
            "SYSTEM_PROMPT = '''You are an expert, patient, and friendly Python Learning Assistant.\n",
            "Your mission is to help beginner students master Python programming.\n",
            "Follow these principles:\n",
            "1. Explain concepts in clear, simple English without unnecessary jargon.\n",
            "2. Provide idiomatic, clean, and bug-free Python code examples.\n",
            "3. Break down code step-by-step or line-by-line when explaining snippets.\n",
            "4. When diagnosing errors, clearly explain the cause and provide the exact fix.\n",
            "5. Always encourage the student with beginner-friendly practice questions and hints.\n",
            "'''\n",
            "\n",
            "class SFTDataset(Dataset):\n",
            "    def __init__(self, records, tokenizer, max_len=512):\n",
            "        self.features = []\n",
            "        for r in records:\n",
            "            user_msg = r['instruction'].strip()\n",
            "            if r.get('input', '').strip():\n",
            "                user_msg += f\"\\n\\n```python\\n{r['input'].strip()}\\n```\"\n",
            "            \n",
            "            prompt_str = f'<|im_start|>system\\n{SYSTEM_PROMPT.strip()}<|im_end|>\\n<|im_start|>user\\n{user_msg}<|im_end|>\\n<|im_start|>assistant\\n'\n",
            "            resp_str = f\"{r['output'].strip()}<|im_end|>\\n\"\n",
            "            \n",
            "            p_ids = tokenizer.encode(prompt_str, add_special_tokens=False)\n",
            "            r_ids = tokenizer.encode(resp_str, add_special_tokens=False)\n",
            "            \n",
            "            full_ids = p_ids + r_ids\n",
            "            if len(full_ids) > max_len:\n",
            "                full_ids = full_ids[:max_len]\n",
            "            \n",
            "            # Loss masking: Prompt tokens are assigned label -100 so loss is computed ONLY on response tokens\n",
            "            p_len = min(len(p_ids), len(full_ids))\n",
            "            labels = [-100] * p_len + full_ids[p_len:]\n",
            "            mask = [1] * len(full_ids)\n",
            "            \n",
            "            # Pre-training audit guard: Ensure example has at least one trainable response token\n",
            "            trainable_tokens = sum(1 for lbl in labels if lbl != -100)\n",
            "            assert trainable_tokens > 0, f\"FATAL: Example '{r['instruction'][:35]}' has 0 trainable tokens after truncation!\"\n",
            "            \n",
            "            # Store native Python lists to ensure clean DataCollatorForSeq2Seq padding and prevent NumPy 2.x tensor concatenation errors\n",
            "            self.features.append({\n",
            "                'input_ids': full_ids,\n",
            "                'attention_mask': mask,\n",
            "                'labels': labels\n",
            "            })\n",
            "            \n",
            "    def __len__(self):\n",
            "        return len(self.features)\n",
            "        \n",
            "    def __getitem__(self, idx):\n",
            "        return self.features[idx]\n",
